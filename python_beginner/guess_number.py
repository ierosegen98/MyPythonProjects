"""Программа генерирует случайное число в диапазоне от 1 до x и просит пользователя угадать это число.
Если догадка пользователя больше случайного числа, то программа выводит сообщение 'Ваше число больше загаданного, попробуйте еще разок'.
Если догадка меньше случайного числа, то программа выводит сообщение 'Ваше число меньше загаданного, попробуйте еще разок'.
Если пользователь угадывает число, то программа выводит сообщение 'Вы угадали за такое количество попыток, поздравляем!'."""

import random


def is_valid(guess: str, edge_num: int) -> bool:
    """Функция проверяет, ввёл ли пользователь целое число от 1 до edge_num"""
    return guess.isdigit() and int(guess) in range(1, edge_num + 1)


def play_game(edge_num: int) -> str:
    """Запускает игру в заданном диапазоне.

    Генерирует число и проверяет догадки пользователя.
    """
    count = 0
    num = random.randint(1, edge_num)

    while True:
        guess = input(f'Введите число от 1 до {edge_num}: ')
        if not is_valid(guess, edge_num):
            print(f'А может быть все-таки введем целое число от 1 до {edge_num}?')
            continue
        
        current_num = int(guess)
        count += 1
        if current_num > num:
            print('Ваше число больше загаданного, попробуйте еще разок')
        elif current_num < num:
            print('Ваше число меньше загаданного, попробуйте еще разок')
        else:
            if count == 1:
                print(f'Вы угадали за {count} попытку, поздравляем!')
                break
            elif 2 <= count <= 4:
                print(f'Вы угадали за {count} попытки, поздравляем!')
                break
            else:
                print(f'Вы угадали за {count} попыток, поздравляем!')
                break


print('Добро пожаловать в числовую угадайку')
print('Давайте решим в каком диапазоне будем угадывать')

while True:
    edge_num = int(input('Введите правую границу диапазона: '))
    play_game(edge_num)

    answer = input('Хотите сыграть еще раз? (Да/Нет): ').lower()

    if answer in {"нет", "н", "no"}:
        print('Спасибо, что играли в числовую угадайку. Еще увидимся...')
        break
    elif answer not in {"да", "д", "yes"}:
        print('Простите, я вас не понял, так вы хотите поиграть?')

